package provider

// maxInlineContentBytes — защитный порог для чтения содержимого объекта целиком
// в строковый атрибут state (content).
//
// Реальный жёсткий предел — размер gRPC-сообщения между Terraform core и
// провайдером, зашитый в terraform-plugin-go/go-plugin (по умолчанию ~256 МиБ,
// 268435456 байт) и НЕ настраиваемый из кода провайдера. Мы специально берём
// порог заметно ниже него: gRPC-сообщение несёт не только сырые байты content,
// а весь diagnostics+state (plan/state diff, msgpack-обёртка типов Terraform,
// у ресурса ещё и plan рядом), так что накладные расходы легко съедают запас,
// который выглядел бы безопасным впритык к 256 МиБ.
//
// Если объект больше этого порога, читать его в content не пытаемся вообще —
// возвращаем понятную ошибку раньше, чем до дела дойдёт gRPC (который просто
// уронит плагин с "ResourceExhausted", как это уже один раз произошло на
// объекте ~600 МБ). Для больших объектов используйте download_path у
// platformcraft_object (data source) — он качает объект потоково на диск, в
// обход state целиком.
const maxInlineContentBytes int64 = 64 * 1024 * 1024 // 64 MiB
